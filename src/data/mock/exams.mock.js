export function flattenExamQuestions(exam) {
  return (exam?.sections || []).flatMap((section) =>
    (section.questionIds || []).map((questionId) => ({
      questionId,
      sectionId: section.id,
      sectionName: section.name,
      subjectId: section.subjectId,
    })),
  )
}
