import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import {
  AlertTriangle,
  Bell,
  CalendarCheck,
  CalendarClock,
  CheckCheck,
  CheckSquare,
  LifeBuoy,
  Megaphone,
  MessageSquare,
  PlayCircle,
  Video,
  X,
} from 'lucide-react'
import { notificationService } from '../services/notification.service.js'
import { groupNotifications, notificationCategory, notificationPriority, NOTIFICATION_CATEGORY_LABEL } from '../lib/notification-visual.js'
import { relativeTime } from '../lib/time.js'
import { useAuth } from '../context/AuthContext.jsx'
import { EmptyState, Skeleton } from '../ui/states.jsx'

/* Notification inbox popover. Notifications are generated by services at the
   moment an event happens, so every entry links to a real record. Priority and
   read state are rendered independently (see lib/notification-visual.js). */

const CATEGORY_ICON = {
  exam: CalendarClock,
  class: Video,
  recording: PlayCircle,
  doubt: MessageSquare,
  institute: Megaphone,
  support: LifeBuoy,
  approval: CheckSquare,
  attendance: CalendarCheck,
  general: Bell,
}

function NotificationRow({ item, onSelect }) {
  const priority = notificationPriority(item)
  const category = notificationCategory(item)
  const Icon = CATEGORY_ICON[category] || Bell
  const isRead = Boolean(item.read)

  return (
    <Link
      to={item.link || '#'}
      onClick={() => onSelect(item)}
      className="notif-row"
      data-priority={priority}
      data-read={isRead ? 'true' : 'false'}
      data-category={category}
      aria-label={`${priority === 'high' ? 'Important, ' : ''}${isRead ? 'Read' : 'Unread'} ${category} notification: ${item.title}`}
    >
      <span className="notif-rail" aria-hidden="true" />
      <span className="notif-icon" aria-hidden="true">
        <Icon className="h-3.5 w-3.5" />
      </span>
      <span className="notif-content">
        <span className="notif-headline">
          <span className="notif-title">{item.title}</span>
          {priority === 'high' ? (
            <span className="notif-priority">
              <AlertTriangle className="h-2.5 w-2.5" aria-hidden="true" /> Important
            </span>
          ) : null}
          {!isRead ? <span className="notif-unread" aria-hidden="true" /> : null}
        </span>
        <span className="notif-body clamp-2">{item.body}</span>
        <span className="notif-meta">
          <time dateTime={item.createdAt}>{relativeTime(item.createdAt)}</time>
          <span className="notif-category">{NOTIFICATION_CATEGORY_LABEL[category]}</span>
        </span>
      </span>
    </Link>
  )
}

export default function NotificationInbox({ align = 'right' }) {
  const { user } = useAuth()
  const [open, setOpen] = useState(false)
  const [items, setItems] = useState([])
  const [loading, setLoading] = useState(false)
  const [unread, setUnread] = useState(0)
  const panelRef = useRef(null)
  const buttonRef = useRef(null)

  const load = useCallback(async () => {
    if (!user) return
    setLoading(true)
    try {
      const result = await notificationService.listForUser(user.id)
      setItems(result.items)
      setUnread(result.unreadCount)
    } catch {
      setItems([])
    } finally {
      setLoading(false)
    }
  }, [user])

  useEffect(() => {
    load()
  }, [load])

  useEffect(() => {
    if (!open) return
    const onClick = (event) => {
      if (panelRef.current?.contains(event.target) || buttonRef.current?.contains(event.target)) return
      setOpen(false)
    }
    const onKey = (event) => event.key === 'Escape' && setOpen(false)
    document.addEventListener('mousedown', onClick)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('mousedown', onClick)
      document.removeEventListener('keydown', onKey)
    }
  }, [open])

  const markAll = async () => {
    if (!user) return
    await notificationService.markAllRead(user.id)
    setItems((current) => current.map((item) => ({ ...item, read: true })))
    setUnread(0)
  }

  const markOne = async (id) => {
    await notificationService.markRead(id)
    setItems((current) => current.map((item) => (item.id === id ? { ...item, read: true } : item)))
    setUnread((current) => Math.max(0, current - 1))
  }

  const groups = useMemo(() => groupNotifications(items), [items])

  const select = (item) => {
    if (!item.read) markOne(item.id)
    setOpen(false)
  }

  return (
    <div className="relative">
      <button
        ref={buttonRef}
        type="button"
        onClick={() => setOpen((value) => !value)}
        className="icon-btn relative"
        aria-label={`Notifications${unread ? `, ${unread} unread` : ''}`}
        aria-expanded={open}
        aria-haspopup="dialog"
      >
        <Bell className="h-4 w-4" />
        {unread > 0 ? (
          <span
            className="absolute -right-0.5 -top-0.5 flex h-[15px] min-w-[15px] items-center justify-center rounded-full bg-[var(--sky-700)] px-1 text-[9px] font-semibold text-white"
            data-unread-badge={unread}
          >
            {unread > 9 ? '9+' : unread}
          </span>
        ) : null}
      </button>

      {open ? (
        <div
          ref={panelRef}
          role="dialog"
          aria-label="Notifications"
          data-notification-panel
          className={`notif-panel absolute top-[42px] z-50 w-[min(92vw,380px)] ${align === 'right' ? 'right-0' : 'left-0'}`}
        >
          <div className="notif-header">
            <p className="notif-heading">Notifications</p>
            <span className="notif-count" data-unread-count={unread} aria-live="polite">
              {unread} unread
            </span>
            <button type="button" onClick={() => setOpen(false)} className="notif-close" aria-label="Close notifications">
              <X className="h-3.5 w-3.5" />
            </button>
          </div>

          <div className="notif-toolbar">
            <span className="notif-toolbar-hint">
              {items.length} update{items.length === 1 ? '' : 's'}
            </span>
            <button
              type="button"
              onClick={markAll}
              disabled={!unread}
              className="notif-mark-all"
              data-action="mark-all-read"
            >
              <CheckCheck className="h-3 w-3" /> Mark all as read
            </button>
          </div>

          <div className="notif-scroll thin-scroll" role="log" aria-label="Notification list">
            {loading ? (
              <div className="space-y-2 p-3">
                <Skeleton className="h-10" />
                <Skeleton className="h-10" />
                <Skeleton className="h-10" />
              </div>
            ) : items.length === 0 ? (
              <EmptyState compact icon={Bell} title="You are all caught up" description="New examinations, class starts and replies will appear here." />
            ) : (
              groups.map((group) => (
                <div className="notif-group" key={group.key}>
                  <p className="notif-group-label" data-group={group.key}>
                    {group.label} <span className="notif-group-count">{group.items.length}</span>
                  </p>
                  {group.items.map((item) => (
                    <NotificationRow key={item.id} item={item} onSelect={select} />
                  ))}
                </div>
              ))
            )}
          </div>
        </div>
      ) : null}
    </div>
  )
}
